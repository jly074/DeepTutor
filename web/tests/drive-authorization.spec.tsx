import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { beforeEach, expect, it, vi } from 'vitest'
import DriveAuthorization from '@/components/learning/DriveAuthorization'
const request = vi.hoisted(() => vi.fn())
vi.mock('@/lib/drive-sources-api', () => ({ driveRequest: request }))
vi.mock('react-i18next', () => ({ useTranslation: () => ({ t: (s: string) => s }) }))
beforeEach(() => { request.mockReset(); sessionStorage.clear() })
it('shows missing configuration without requesting or collecting credentials', async () => {
  request.mockResolvedValue({ state: 'not_configured' })
  render(<DriveAuthorization workspaceId="a" />)
  expect(await screen.findByText('driveAuth.not_configured')).toBeVisible()
  expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
  expect(request.mock.calls.map(x => x[0])).toEqual(['/oauth/status'])
})
it('requires a folder ID and explicit consent before beginning authorization', async () => {
  request.mockResolvedValueOnce({ state: 'needs_authorization' }).mockRejectedValueOnce(new Error('safe'))
  render(<DriveAuthorization workspaceId="a" />)
  const button = await screen.findByRole('button', { name: 'driveAuth.connect' })
  expect(button).toBeDisabled()
  fireEvent.change(screen.getByRole('textbox'), { target: { value: 'https://drive.example/folders/id' } })
  fireEvent.click(screen.getByRole('checkbox'))
  expect(button).toBeDisabled()
  fireEvent.change(screen.getByRole('textbox'), { target: { value: 'stable-folder-id' } })
  fireEvent.click(button)
  expect(await screen.findByRole('alert')).toHaveTextContent('driveAuth.error')
  const call = request.mock.calls[1]
  expect(call.slice(0,3)).toEqual(['/oauth/start','a','live'])
  expect(JSON.parse(call[3].body)).toMatchObject({ folder_id: 'stable-folder-id', consent: true })
  expect(JSON.parse(call[3].body).browser_nonce).toMatch(/^[a-f0-9]{64}$/)
})
it('refuses a callback from a different workspace without posting the code', async () => {
  request.mockResolvedValue({ state: 'needs_authorization' })
  sessionStorage.setItem('drive.oauth.pending', JSON.stringify({ workspace: 'other', state: 's', nonce: 'n', expires: Date.now()+10000 }))
  sessionStorage.setItem('drive.oauth.callback', JSON.stringify({ state: 's', code: 'SYNTHETIC' }))
  render(<DriveAuthorization workspaceId="a" />)
  await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('driveAuth.error'))
  expect(request.mock.calls.some(c => c[0] === '/oauth/complete')).toBe(false)
  expect(sessionStorage.getItem('drive.oauth.callback')).toBeNull()
})
it('clears malformed callback storage and restores a usable retry action', async () => {
  request.mockResolvedValue({ state: 'needs_authorization' })
  sessionStorage.setItem('drive.oauth.callback', '{bad')
  sessionStorage.setItem('drive.oauth.pending', '{bad')
  render(<DriveAuthorization workspaceId="a" />)
  expect(await screen.findByRole('button', { name: 'driveAuth.connect' })).toBeDisabled()
  expect(screen.getByRole('alert')).toHaveTextContent('driveAuth.error')
  expect(sessionStorage.getItem('drive.oauth.callback')).toBeNull()
  expect(sessionStorage.getItem('drive.oauth.pending')).toBeNull()
})
